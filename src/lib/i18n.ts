const LANGUAGE_MAP = new Map(SITE_LANGUAGES.map((l) => [l.code, l]));

export function isSupportedLanguage(code: string | null | undefined): code is string {
  return !!code && LANGUAGE_MAP.has(code);
}

export function getLanguageMeta(code: string): SupportedLanguage {
  return LANGUAGE_MAP.get(code) ?? (LANGUAGE_MAP.get(DEFAULT_LANGUAGE) as SupportedLanguage);
}

/** "tr-TR" / "zh-Hans" / "nb" gibi tarayıcı kodlarını desteklenen koda çevirir. */
export function matchBrowserLanguage(raw: string | undefined | null): string | null {
  if (!raw) return null;
  const lower = raw.toLowerCase();
  if (lower.startsWith("zh")) return "zh";
  if (lower.startsWith("nb") || lower.startsWith("nn")) return "no";
  if (lower.startsWith("iw")) return "he";
  const base = lower.split("-")[0] ?? "";
  return isSupportedLanguage(base) ? base : null;
}

export function getSiteLanguage(): string {
  if (typeof window === "undefined") return DEFAULT_LANGUAGE;
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (isSupportedLanguage(stored)) return stored;
  } catch {
    /* localStorage kapalı olabilir */
  }
  return matchBrowserLanguage(navigator.language) ?? DEFAULT_LANGUAGE;
}

/** <html lang> ve dir (RTL diller için) değerlerini günceller. */
export function applyDocumentLanguage(code: string) {
  if (typeof document === "undefined") return;
  const meta = getLanguageMeta(code);
  document.documentElement.lang = meta.code;
  document.documentElement.dir = meta.dir;
}

export function setSiteLanguage(langCode: string) {
  if (typeof window === "undefined" || !isSupportedLanguage(langCode)) return;
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, langCode);
  } catch {
    /* yoksay */
  }
  applyDocumentLanguage(langCode);
  window.dispatchEvent(new CustomEvent(LANGUAGE_EVENT, { detail: langCode }));
}

export function t(
  key: TranslationKey,
  langCode?: string,
  vars?: Record<string, string | number>,
): string {
  const lang = langCode ?? getSiteLanguage();
  const raw = TRANSLATIONS[lang]?.[key] ?? EN[key] ?? TR[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] !== undefined ? String(vars[name]) : `{${name}}`,
  );
}

/**
 * Site dili hook'u. SSR ile birebir aynı çıktıyı üretmek için ilk render her zaman
 * varsayılan dildir; gerçek dil mount sonrasında okunur (hydration uyuşmazlığı olmaz).
 */
export function useSiteLanguage() {
  const [lang, setLang] = useState<string>(DEFAULT_LANGUAGE);

  useEffect(() => {
    const initial = getSiteLanguage();
    setLang(initial);
    applyDocumentLanguage(initial);

    const onChange = (e: Event) => {
      const detail = (e as CustomEvent<string>).detail;
      if (isSupportedLanguage(detail)) setLang(detail);
    };
    const onStorage = (e: StorageEvent) => {
      if (e.key === LANGUAGE_STORAGE_KEY && isSupportedLanguage(e.newValue)) {
        setLang(e.newValue);
        applyDocumentLanguage(e.newValue);
      }
    };
    window.addEventListener(LANGUAGE_EVENT, onChange);
    window.addEventListener("storage", onStorage);
    return () => {
      window.removeEventListener(LANGUAGE_EVENT, onChange);
      window.removeEventListener("storage", onStorage);
    };
  }, []);

  const changeLanguage = useCallback((code: string) => setSiteLanguage(code), []);
  const translate = useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) => t(key, lang, vars),
    [lang],
  );

  return {
    siteLang: lang,
    setSiteLang: changeLanguage,
    t: translate,
    meta: getLanguageMeta(lang),
  };
}
